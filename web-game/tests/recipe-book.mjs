import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
import {launchTestBrowser} from './launch.mjs';

const browser=await launchTestBrowser(),page=await browser.newPage({viewport:{width:1280,height:720}}),errors=[];
page.on('pageerror',error=>errors.push(error.message));page.on('console',message=>{if(message.type()==='error')errors.push(message.text());});
const gameState=()=>page.evaluate(()=>{const g=window.__stonewakeGame;return {bag:g.items.slots.snapshot(),grid:(g.inventory.mode==='station'?g.items.station(g.inventory.cell):g.items.personal).snapshot(),cursor:g.items.cursor};});
try{
  const url=new URL(process.env.STONEWAKE_URL||'http://127.0.0.1:5173/');url.searchParams.set('test','1');
  await page.goto(url.href,{waitUntil:'networkidle'});await page.waitForFunction(()=>window.__stonewakeGame?.loaded);
  await page.locator('#resume').click();await page.waitForFunction(()=>document.pointerLockElement===document.querySelector('#game'));
  await page.evaluate(()=>{const g=window.__stonewakeGame;g.items.slots.set(9,{id:'wood',count:2,damage:0});g.items.slots.set(10,{id:'plank',count:3,damage:0});g.items.slots.set(11,{id:'stick',count:2,damage:0});});
  await page.keyboard.press('KeyE');await page.locator('#recipe-book-toggle').click();
  assert.equal(await page.locator('#recipe-book').count(),1);
  await page.locator('#recipe-search').fill('plank');
  assert.equal(await page.locator('.book-recipe').count(),1);
  assert.match(await page.locator('[data-recipe="planks"]').getAttribute('class'),/craftable/);
  const before=await gameState();await page.locator('[data-recipe="planks"]').click();const placed=await gameState();
  assert.equal(placed.grid[0].id,'wood');assert.equal(placed.grid[0].count,1);
  assert.equal(placed.bag[9].count,1);assert.equal(placed.cursor.count,0);
  assert.equal(before.bag[9].count,placed.bag[9].count+placed.grid[0].count);
  assert.match(await page.locator('#craft-output').textContent(),/Wood Plank/);
  await mkdir('.artifacts',{recursive:true});await page.screenshot({path:'.artifacts/recipe-book-personal.png'});
  await page.locator('#recipe-search').fill('wayfinder');
  assert.match(await page.locator('[data-recipe="wayfinder"]').getAttribute('class'),/unavailable/);
  const unavailableBefore=await gameState();await page.locator('[data-recipe="wayfinder"]').click();
  assert.deepEqual(await gameState(),unavailableBefore);
  assert.match(await page.locator('#book-message').textContent(),/Missing/);
  await page.locator('#recipe-search').fill('');await page.locator('[data-category="equipment"]').click();
  assert.equal(await page.locator('.book-recipe').count(),0);
  await page.locator('[data-category="building"]').click();assert.ok(await page.locator('.book-recipe').count()>0);
  await page.locator('#recipe-book-toggle').click();assert.equal(await page.locator('#recipe-book').count(),0);
  await page.locator('#craft-output').click();assert.equal((await gameState()).cursor.id,'plank');
  await page.locator('#close-inventory').click();
  await page.evaluate(()=>{const g=window.__stonewakeGame;g.items.personal.load([]);g.items.cursor={id:'',count:0,damage:0};
    g.items.slots.set(10,{id:'plank',count:3,damage:0});g.items.slots.set(11,{id:'stick',count:2,damage:0});g.openInventory('station','book-fixture');});
  await page.locator('#recipe-book-toggle').click();await page.locator('[data-category="equipment"]').click();await page.locator('#recipe-search').fill('wood pickaxe');
  assert.match(await page.locator('[data-recipe="wood_pickaxe"]').getAttribute('class'),/craftable/);
  const stationBefore=await gameState();await page.locator('[data-recipe="wood_pickaxe"]').click();const stationPlaced=await gameState();
  assert.deepEqual(stationPlaced.grid.map(s=>s.id),['plank','plank','plank','','stick','','','stick','']);
  assert.equal(stationBefore.bag[10].count,stationPlaced.bag[10].count+3);
  assert.equal(stationBefore.bag[11].count,stationPlaced.bag[11].count+2);
  await page.screenshot({path:'.artifacts/recipe-book-station.png'});
  await page.locator('#craft-output').click();assert.equal((await gameState()).cursor.id,'wood_pickaxe');
  await page.locator('#close-inventory').click();await page.evaluate(()=>window.__stonewakeGame.saveNow());
  await page.reload({waitUntil:'networkidle'});await page.waitForFunction(()=>window.__stonewakeGame?.loaded);
  assert.equal(await page.evaluate(()=>window.__stonewakeGame.items.slots.count('wood_pickaxe')),1);
  await page.locator('#resume').click();await page.waitForFunction(()=>document.pointerLockElement===document.querySelector('#game'));
  await page.keyboard.press('KeyE');
  const pickaxe=page.locator('[data-grid="bag"][data-item-id="wood_pickaxe"]');await pickaxe.hover();
  assert.match(await page.locator('#item-tooltip').textContent(),/Wood Pickaxe/);
  assert.match(await page.locator('#item-tooltip').textContent(),/Durability/);
  assert.ok(await pickaxe.locator('.item-icon').evaluate(img=>img.complete&&img.naturalWidth>0));
  await page.screenshot({path:'.artifacts/crafting-tooltip.png'});
  await page.setViewportSize({width:1024,height:768});await page.locator('#recipe-book-toggle').click();
  const bounds=await page.evaluate(()=>{const a=document.querySelector('#recipe-book').getBoundingClientRect(),b=document.querySelector('.inventory-panel').getBoundingClientRect();
    return {book:[a.left,a.right,a.top,a.bottom],panel:[b.left,b.right,b.top,b.bottom],inner:[innerWidth,innerHeight]};});
  assert.ok(bounds.book[0]>=0&&bounds.book[1]<=bounds.inner[0]&&bounds.panel[0]>=0&&bounds.panel[1]<=bounds.inner[0]);
  await page.screenshot({path:'.artifacts/recipe-book-1024.png'});
  assert.deepEqual(errors,[]);
  console.log('RECIPE BOOK PASS: open/close, search, categories, craftability, safe 2x2/3x3 population, output, tooltip/icons, 1024px layout and IndexedDB reload; no browser errors');
}finally{await browser.close();}
